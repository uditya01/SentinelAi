import os
from datetime import datetime

from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
)

REPORT_FOLDER = "reports/generated"

os.makedirs(REPORT_FOLDER, exist_ok=True)


class ReportGenerator:

    @staticmethod
    def generate(scan_result):

        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")

        filename = f"scan_{timestamp}.pdf"

        filepath = os.path.join(REPORT_FOLDER, filename)

        doc = SimpleDocTemplate(filepath)

        styles = getSampleStyleSheet()

        elements = []

        # -------------------------
        # Title
        # -------------------------

        title = Paragraph(
            "<b><font size=22>SENTINEL AI</font></b>",
            styles["Title"],
        )

        elements.append(title)

        elements.append(
            Paragraph(
                "Security Scan Report",
                styles["Heading2"],
            )
        )

        elements.append(Spacer(1, 20))

        # -------------------------
        # Summary Table
        # -------------------------

        data = [
            ["Date", datetime.now().strftime("%d %B %Y")],
            ["Time", datetime.now().strftime("%H:%M:%S")],
            ["Files Scanned", str(scan_result.scanned_files)],
            ["Skipped Files", str(scan_result.skipped_files)],
            ["Threats Found", str(scan_result.threats_found)],
            ["Total Data", f"{scan_result.total_mb:.2f} MB"],
        ]

        table = Table(data, colWidths=[180, 250])

        table.setStyle(
            TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), colors.darkblue),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),

                ("GRID", (0, 0), (-1, -1), 1, colors.grey),

                ("BACKGROUND", (0, 1), (0, -1), colors.lightgrey),

                ("BOTTOMPADDING", (0, 0), (-1, 0), 10),
            ])
        )

        elements.append(table)

        elements.append(Spacer(1, 25))

        # -------------------------
        # Scan Result
        # -------------------------

        if scan_result.threats_found == 0:

            elements.append(
                Paragraph(
                    "<font color='green'><b>✔ SYSTEM CLEAN</b></font>",
                    styles["Heading2"],
                )
            )

        else:

            elements.append(
                Paragraph(
                    "<font color='red'><b>⚠ THREATS DETECTED</b></font>",
                    styles["Heading2"],
                )
            )

            elements.append(Spacer(1, 15))

            for file in scan_result.threat_files:

                elements.append(
                    Paragraph(
                        f"<b>Threat Name:</b> {file.threat.malware_name}",
                        styles["Heading3"],
                    )
                )

                elements.append(
                    Paragraph(
                        f"<b>Verdict:</b> {file.threat.verdict}",
                        styles["Normal"],
                    )
                )

                elements.append(
                    Paragraph(
                        f"<b>Detection Source:</b> {file.threat.source}",
                        styles["Normal"],
                    )
                )

                elements.append(
                    Paragraph(
                        f"<b>File:</b> {file.path}",
                        styles["Normal"],
                    )
                )

                elements.append(
                    Paragraph(
                        f"<b>SHA256:</b> {file.sha256}",
                        styles["Normal"],
                    )
                )

                elements.append(Spacer(1, 15))

        # -------------------------
        # Footer
        # -------------------------

        elements.append(Spacer(1, 20))

        elements.append(
            Paragraph(
                "Generated by Sentinel AI",
                styles["Italic"],
            )
        )

        doc.build(elements)

        return filepath